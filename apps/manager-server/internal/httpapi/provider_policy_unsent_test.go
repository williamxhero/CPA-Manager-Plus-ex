// F2 uses a SEEDED DURABLE CRASH FIXTURE, not a claim that a production crash
// hook generated this state. Public APIs create the real issued binding, ON
// intent, official source, successful job, started capture and completion event.
// A before-proof management refusal stops the automatic consumer before a gate
// journal exists. Only the decision CAS's durable Pending/LastSeq image is then
// seeded into temporary SQLite to represent crash-after-decision-before-
// SaveProviderGate. No gate command, Core receipt, binding or balance is seeded.
func TestProviderPolicySeededUnsentDecisionRetiresAcrossOFFAndReenable(t *testing.T) {
	// The deliberately seeded crash image must remain quiescent until its
	// exact OFF-generation retirement checks; fresh recovery starts real Run.
	f := newPolicyUnsentFixture(t, false)
	oldJob, gateBefore, revisionBefore := seedPolicyUnsentCrashDecision(t, f)
	generation := f.state.Generation
	owner := f.state.Owner
	f.closeManager()
	f.openManager() // Prove the decision is durable, not a goroutine-local fixture.
	if state := f.status(); state.State != "pending" || !state.Enabled || state.Generation != generation {
		t.Fatalf("seeded durable crash fixture did not survive SQLite reopen: %+v", state)
	}
	f.update(false)
	f.reconcile()
	f.reconcile()
	f.assertNoPending()
	state := f.status()
	if state.Enabled || state.Locked || state.Generation != generation+1 || state.Owner != owner || state.OwnPaused {
		t.Fatalf("OFF failed to retire a provably unsent old-generation decision: %+v", state)
	}
	assertPolicyUnsentNoGateMutation(t, f, gateBefore, revisionBefore)
	f.update(true)
	f.reconcile()
	f.assertNoPending()
	if f.state.Generation != generation+2 || f.state.Owner != owner || !f.state.Enabled || f.state.OwnPaused {
		t.Fatal("new ON generation failed or reused the old generation's successful low")
	}
	assertPolicyUnsentNoGateMutation(t, f, gateBefore, revisionBefore)
	f.assertFreshPauseAndRecovery(oldJob.ID, revisionBefore)
	if f.queries.Load() != 3 {
		t.Fatalf("OFF/reconcile/ON performed a money query or skipped the required new successes: %d", f.queries.Load())
	}
	t.Log("F2 SEEDED_DURABLE_CRASH_FIXTURE: temporary SQLite reopened; OFF retired unsent Pending; new ON required new actual successful low/high queries; no production crash-path generation claimed")
}

func TestProviderPolicySeededUnsentDecisionRetiresAfterQueryReplacement(t *testing.T) {
	f := newPolicyUnsentFixture(t, false)
	oldJob, gateBefore, revisionBefore := seedPolicyUnsentCrashDecision(t, f)
	generation, owner := f.state.Generation, f.state.Owner
	f.closeManager()
	f.openManager()
	if state := f.status(); state.State != "pending" || state.Generation != generation {
		t.Fatal("seeded unsent Pending did not survive SQLite reopen")
	}
	// Same enabled generation and same runtime group, but Manager query v1 is
	// replaced by v2 through the public CAS endpoint. The explicit controlled
	// key remains the actual runtime key; no guessed shared-wallet authority.
	replacement := f.configureOfficial()
	if replacement.Version != 2 || replacement.LastSuccess != nil || replacement.Attempt != nil {
		t.Fatalf("query replacement retained v1 observations instead of requiring a new success: %+v", replacement)
	}
	f.reconcile()
	f.reconcile()
	f.assertNoPending()
	state := f.status()
	if !state.Enabled || state.Locked || state.Generation != generation || state.Owner != owner || state.OwnPaused {
		t.Fatalf("same-generation superseded unsent decision remained blocking: %+v", state)
	}
	assertPolicyUnsentNoGateMutation(t, f, gateBefore, revisionBefore)
	f.assertFreshPauseAndRecovery(oldJob.ID, revisionBefore)
	if f.state.Generation != generation || f.version != 2 || f.queries.Load() != 3 {
		t.Fatal("query v2 recovery changed intent generation, reused v1, or fabricated a successful query")
	}
	t.Log("F2 SEEDED_DURABLE_CRASH_FIXTURE: same generation, replaced Manager query v1->v2; obsolete unsent decision retired without a gate mutation; new v2 successes drive actual Core pause/clear")
}

// F3 is deliberately NOT the accepted-but-ACK-lost branch already covered by
// provider_policy_recovery_test.go. The management bridge refuses the very first
// operations POST BEFORE FORWARDING, after production SaveProviderGate. Both the
// journal and policy Pending here are generated by production code, not seeded.
func TestProviderPolicyUnacceptedOldBootJournalRetiresAfterActualCoreRestart(t *testing.T) {
	// Own exactly one rejected-before-forward lifecycle attempt before the
	// crash/restart. The fresh new-boot phase below runs the actual worker.
	f := newPolicyUnsentFixture(t, false)
	oldBinding := f.state.Binding
	intentGeneration, owner := f.state.Generation, f.state.Owner
	revisionBefore := f.revision()
	f.wire.rejectOperations.Store(true)
	oldJob := f.query("0.05")
	attempt, stopAttempt := context.WithTimeout(context.Background(), 15*time.Second)
	_ = f.manager.AppContext().ProviderPolicyService.Reconcile(attempt)
	stopAttempt()
	state := f.status()
	if !state.Enabled || state.State != "pending" || state.OwnPaused || state.Applied {
		t.Fatalf("never-forwarded decision was optimistically applied or not pending: %+v", state)
	}
	oldGate := f.monetaryGate()
	if oldGate.Generation != 1 || oldGate.Settled || oldGate.Applied || oldGate.OwnPaused || oldGate.State != "pending" {
		t.Fatalf("real same-boot missing operation was not honestly unknown: %+v", oldGate)
	}
	record, journal := readPolicyUnsentJournal(t, f, oldGate.SubjectID)
	if journal.Operation.OpID == "" || journal.Operation.Scope != oldBinding.Scope || journal.Operation.ExpectedGateRevision != revisionBefore || journal.Operation.Action != "pause" || !strings.HasPrefix(journal.Operation.EvidenceID, "balance/") || journal.Receipt.OpID != "" {
		t.Fatal("production failed to persist a genuine immutable unaccepted monetary gate journal")
	}
	attemptedBefore, forwarded, accepted := f.wire.snapshot()
	if len(attemptedBefore) != 1 || len(forwarded) != 0 || len(accepted) != 0 {
		t.Fatalf("fixture must reject before Core, not discard an ACK: attempted=%d forwarded=%d accepted=%d", len(attemptedBefore), len(forwarded), len(accepted))
	}
	var sentOperation, durableOperation any
	if err := json.Unmarshal(attemptedBefore[0], &sentOperation); err != nil {
		t.Fatal(err)
	}
	if err := json.Unmarshal(journal.RawOperation, &durableOperation); err != nil || !reflect.DeepEqual(sentOperation, durableOperation) {
		t.Fatal("attempted HTTP body does not match the genuine durable immutable journal")
	}
	f.coreRequest(http.MethodGet, policyUnsentOperationsPath+"/"+journal.Operation.OpID, nil, http.StatusNotFound, nil)
	if f.revision() != revisionBefore {
		t.Fatal("never-forwarded old command nevertheless advanced the real Core ledger")
	}
	// No query or worker is left running when the actual owned ordinary Core
	// process is killed/waited and restarted on the SAME durable data directory.
	f.closeManager()
	f.core.restart()
	f.openManager()
	f.wire.rejectOperations.Store(false)
	f.readIssuedBinding() // Actual management API negotiation, not patching old scope.
	newBinding := f.state.Binding
	if newBinding.Scope.BootEpoch == oldBinding.Scope.BootEpoch || newBinding.Scope.InstanceID != oldBinding.Scope.InstanceID || newBinding.Scope.InstanceIncarnation != oldBinding.Scope.InstanceIncarnation || !reflect.DeepEqual(newBinding.Targets, oldBinding.Targets) {
		t.Fatal("restart must change boot while preserving durable instance and issued target identities")
	}
	if f.revision() != revisionBefore {
		t.Fatal("restart advanced gate revision; this would test expired CAS, not the F3 same-revision obsolete-boot case")
	}
	f.coreRequest(http.MethodGet, policyUnsentOperationsPath+"/"+journal.Operation.OpID, nil, http.StatusNotFound, nil)
	// The old HTTP policy precondition must also remain unusable after restart.
	enabled := true
	f.api(http.MethodPut, "/usage-service/provider-policy", pp.Update{Binding: oldBinding, ExpectedGeneration: &intentGeneration, Enabled: &enabled}, http.StatusConflict, nil)
	currentGate := f.monetaryGate()
	if !currentGate.Settled || currentGate.State != "rejected" || currentGate.Applied || currentGate.OwnPaused || currentGate.Generation != oldGate.Generation || currentGate.Reason == "" {
		t.Fatalf("actual old-op 404 plus new issued boot did not definitively settle/reject the old journal: %+v", currentGate)
	}
	app := f.manager.AppContext()
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()
	recovered, err := pg.NewMonetary(f.db, app.ManagerConfigService, app.ResourceCapabilityService).Reconcile(ctx, pg.Binding(newBinding))
	if err != nil || !recovered.Settled || recovered.State != "rejected" || recovered.Applied {
		t.Fatalf("obsolete journal reconciliation was blocking or claimed applied: %+v err=%v", recovered, err)
	}
	f.reconcile()
	f.reconcile()
	f.assertNoPending()
	state = f.status()
	if !state.Enabled || state.Locked || state.State != "observing" || state.Applied || state.OwnPaused || state.Generation != intentGeneration || state.Owner != owner {
		t.Fatalf("retired old boot journal prevented enabled policy recovery: %+v", state)
	}
	unchanged, _ := readPolicyUnsentJournal(t, f, oldGate.SubjectID)
	if unchanged != record {
		t.Fatal("obsolete immutable operation was rebound, rewritten, or given a fabricated durable receipt")
	}
	attempted, forwarded, accepted := f.wire.snapshot()
	if len(attempted) != len(attemptedBefore) || len(forwarded) != 0 || len(accepted) != 0 || f.revision() != revisionBefore || f.queries.Load() != 1 {
		t.Fatal("old body was replayed or old success reused during read-only obsolete-boot recovery")
	}
	// Only a newly started successful official query on the actual new boot may
	// create a new operation. A second fresh high query proves further progress.
	f.assertFreshPauseAndRecovery(oldJob.ID, revisionBefore)
	attempted, forwarded, _ = f.wire.snapshot()
	accepted = f.assertExactReceipts(revisionBefore, "pause", "clear")
	if len(attempted) != len(attemptedBefore)+2 || len(forwarded) != 2 || len(accepted) != 2 || f.queries.Load() != 3 {
		t.Fatal("new-boot fresh query lifecycle retransmitted or duplicated the old command")
	}
	for _, id := range accepted {
		if id == journal.Operation.OpID {
			t.Fatal("never-accepted obsolete old-boot opId was reused for fresh monetary authority")
		}
	}
	f.coreRequest(http.MethodGet, policyUnsentOperationsPath+"/"+journal.Operation.OpID, nil, http.StatusNotFound, nil)
	// Keep the original unaccepted immutable operation auditable even after the
	// current journal has progressed to fresh commands under the new boot.
	inspection := openPolicyUnsentInspection(t, f.cfg.DBPath)
	var oldHistory string
	if err := inspection.QueryRow(`SELECT document FROM provider_gate_history WHERE id=? AND generation=?`, record.ID, record.Generation).Scan(&oldHistory); err != nil || oldHistory != record.Document {
		t.Fatalf("new fresh progress erased/rebound old immutable history: err=%v", err)
	}
	t.Logf("F3 actual ordinary Core starts=%d; production before-forward journal oldBoot=%s newBoot=%s; real old-op 404 at unchanged gateRevision=%d; settled/rejected reason=%s; no old POST replay; new fresh low/high restored progress; process logs=%s", f.core.starts, oldBinding.Scope.BootEpoch, newBinding.Scope.BootEpoch, revisionBefore, currentGate.Reason, f.core.logs)
}

func openPolicyUnsentInspection(t *testing.T, path string) *sql.DB {
	t.Helper()
	inspection, err := sql.Open("sqlite", path)
	if err != nil {
		t.Fatal(err)
	}
	inspection.SetMaxOpenConns(1)
	t.Cleanup(func() { _ = inspection.Close() })
	if _, err := inspection.Exec(`PRAGMA busy_timeout=5000`); err != nil {
		t.Fatal(err)
	}
	return inspection
}

func seedPolicyUnsentCrashDecision(t *testing.T, f *policyUnsentFixture) (ob.Job, pg.Status, uint64) {
	t.Helper()
	gate := f.monetaryGate()
	revision := f.revision()
	if gate.Generation != 0 || gate.OwnPaused || !gate.Settled {
		t.Fatal("seed fixture requires a clean actual monetary gate with no journal")
	}
	// Let real source I/O/capture/job/event complete, but refuse the separate
	// routing proof needed by the policy consumer. No operation can be prepared.
	f.wire.rejectEligibility.Store(true)
	job := f.query("0.05")
	f.wire.rejectEligibility.Store(false)
	f.status() // This is read-only; it cannot consume the persisted completion.
	record, err := f.db.ProviderPolicy(context.Background(), f.state.SubjectID)
	if err != nil {
		t.Fatal(err)
	}
	capture, err := f.db.ProviderPolicyCapture(context.Background(), record.ID, job.ID)
	if err != nil || capture.Generation != record.Generation || capture.Seq <= 0 || record.Generation != f.state.Generation {
		t.Fatalf("seed lacks a real successful ON-generation started capture: %+v err=%v", capture, err)
	}
	var document map[string]any
	if err := json.Unmarshal([]byte(record.Document), &document); err != nil || document["pending"] != nil || document["enabled"] != true {
		t.Fatal("seed must extend the actually API-saved ON intent, not replace a production decision")
	}
	evidence := sha256.Sum256([]byte("seeded-durable-crash-fixture/" + record.ID + "/" + job.ID))
	document["lastSeq"] = capture.Seq
	document["pending"] = struct {
		Binding        pp.Binding `json:"binding"`
		Action         string     `json:"action"`
		Evidence       string     `json:"evidence"`
		GateGeneration int64      `json:"gateGeneration"`
		SourceVersion  string     `json:"sourceVersion"`
		Generation     int64      `json:"generation"`
		AttemptID      string     `json:"attemptId"`
	}{f.state.Binding, "pause", hex.EncodeToString(evidence[:]), gate.Generation, gate.SourceVersion, record.Generation, job.ID}
	raw, err := json.Marshal(document)
	if err != nil {
		t.Fatal(err)
	}
	inspection := openPolicyUnsentInspection(t, f.cfg.DBPath)
	defer inspection.Close() // No inspection connection survives the fixture reopen.
	result, err := inspection.Exec(`UPDATE provider_policies SET document=? WHERE id=? AND generation=? AND document=?`, string(raw), record.ID, record.Generation, record.Document)
	if err != nil {
		t.Fatal(err)
	}
	rows, err := result.RowsAffected()
	if err != nil || rows != 1 {
		t.Fatalf("seeded durable crash fixture failed exact document CAS: rows=%d err=%v", rows, err)
	}
	var journals, history int
	if err := inspection.QueryRow(`SELECT COUNT(*) FROM provider_gate_operations`).Scan(&journals); err != nil {
		t.Fatal(err)
	}
	if err := inspection.QueryRow(`SELECT COUNT(*) FROM provider_gate_history`).Scan(&history); err != nil {
		t.Fatal(err)
	}
	if journals != 0 || history != 0 {
		t.Fatal("fixture is not before SaveProviderGate: a gate journal/history already exists")
	}
	assertPolicyUnsentNoGateMutation(t, f, gate, revision)
	if state := f.status(); state.State != "pending" || !state.Locked || !state.Enabled || state.Applied || state.OwnPaused {
		t.Fatalf("seed did not reproduce pending/locked unsent state: %+v", state)
	}
	t.Logf("SEEDED_DURABLE_CRASH_FIXTURE subject=%s generation=%d attempt=%s captureSeq=%d: ONLY policy Pending/LastSeq seeded after actual public API intent + controlled successful query; gate generation=%d, zero journal/history; not production crash-path generation", record.ID, record.Generation, job.ID, capture.Seq, gate.Generation)
	return job, gate, revision
}

func assertPolicyUnsentNoGateMutation(t *testing.T, f *policyUnsentFixture, gate pg.Status, revision uint64) {
	t.Helper()
	current := f.monetaryGate()
	record, err := f.db.ProviderGate(context.Background(), gate.SubjectID)
	if err != nil {
		t.Fatal(err)
	}
	attempted, forwarded, accepted := f.wire.snapshot()
	if current.Generation != gate.Generation || current.OwnPaused || record.Generation != gate.Generation || record.Document != "" || f.revision() != revision || len(attempted) != 0 || len(forwarded) != 0 || len(accepted) != 0 {
		t.Fatal("provably unsent retirement or intent-only transition mutated a gate or sent a Core operation")
	}
}

type policyUnsentJournal struct {
	Operation struct {
		Scope                rc.Scope `json:"scope"`
		OpID                 string   `json:"opId"`
		Action               string   `json:"action"`
		ExpectedGateRevision uint64   `json:"expectedGateRevision"`
		EvidenceID           string   `json:"evidenceId"`
	}
	Receipt struct {
		OpID string `json:"opId"`
	}
	RawOperation json.RawMessage
}

func readPolicyUnsentJournal(t *testing.T, f *policyUnsentFixture, id string) (store.ProviderGateRecord, policyUnsentJournal) {
	t.Helper()
	record, err := f.db.ProviderGate(context.Background(), id)
	if err != nil {
		t.Fatal(err)
	}
	var journal policyUnsentJournal
	var raw struct {
		Operation json.RawMessage `json:"operation"`
	}
	if record.Generation == 0 || json.Unmarshal([]byte(record.Document), &journal) != nil || json.Unmarshal([]byte(record.Document), &raw) != nil || json.Unmarshal(raw.Operation, &journal.Operation) != nil {
		t.Fatal("actual durable monetary gate journal unavailable")
	}
	journal.RawOperation = raw.Operation
	return record, journal
}
